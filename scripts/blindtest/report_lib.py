def add_heading(text, style, level=0):
    """Titre avec signet TOC cliquable (TocDocTemplate)."""
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def chapter(story, num, title, first_body=None):
    """Chapitre H1 : saut conditionnel anti-orphelin + titre + règle accent + 1er paragraphe."""
    els = [
        add_heading(f'{num}.  {title}', S['h1'], level=0),
        HRFlowable(width='100%', thickness=1.4, color=ACCENT, spaceBefore=2, spaceAfter=10),
    ]
    if first_body is not None:
        els.append(first_body)
    story.append(CondPageBreak(H1_ORPHAN))
    story.append(KeepTogether(els))


def h2(story, text, first_body=None):
    els = [add_heading(text, S['h2'], level=1)]
    if first_body is not None:
        els.append(first_body)
    story.append(KeepTogether(els))


def make_table(header, rows, ratios, style_header='th', style_cell='td',
               repeat=1, font_align=None, width_frac=0.98):
    """Table centrée : toutes cellules Paragraph, largeur ≤ disponible, zébrage palette."""
    total = sum(ratios)
    widths = [r / total * AVAIL_W * width_frac for r in ratios]
    data = [[Paragraph(f'<b>{h}</b>', S[style_header]) for h in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = style_cell
            if font_align and font_align[i] in ('l', 'r', 'c'):
                st = {'l': 'tdl', 'r': 'tdr', 'c': 'td'}[font_align[i]]
            cells.append(c if isinstance(c, (Paragraph, Image)) else Paragraph(str(c), S[st]))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=repeat)
    styles = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 3.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3.5),
    ]
    for i in range(1, len(data)):
        styles.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_EVEN if i % 2 == 1 else TABLE_ROW_ODD))
    t.setStyle(TableStyle(styles))
    return t


def table_block(story, title_text, header, rows, ratios, caption=None, font_align=None, keep=True):
    story.append(Spacer(1, 10))
    t = make_table(header, rows, ratios, font_align=font_align)
    cap = Paragraph(caption, S['caption']) if caption else None
    if keep and len(rows) <= 15:
        els = [t] if not title_text else [Paragraph(title_text, S['h3']), t]
        if cap:
            els.append(cap)
        story.append(KeepTogether(els))
    else:
        if title_text:
            story.append(Paragraph(title_text, S['h3']))
        story.append(t)
        if cap:
            story.append(cap)
    story.append(Spacer(1, 8))


def embed_image(path, max_width=None, max_height=None):
    if max_width is None:
        max_width = AVAIL_W
    if max_height is None:
        max_height = A4[1] * 0.35
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow if ow > max_width else 1.0, max_height / oh if oh > max_height else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def figure_block(story, png_path, caption, max_height=None):
    story.append(Spacer(1, 14))
