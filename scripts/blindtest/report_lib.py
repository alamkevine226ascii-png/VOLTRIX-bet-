def fr(x, nd=4):
    """Format français virgule décimale."""
    if x is None:
        return '—'
    return f'{x:.{nd}f}'.replace('.', ',')


def pct(x, nd=1):
    if x is None:
        return '—'
    return (f'{x * 100:.{nd}f}').replace('.', ',') + ' %'


# ── Modèle de document avec TOC + pieds de page romain/arabe ──
class TocDocTemplate(SimpleDocTemplate):
    def beforeDocument(self):
        # Les footers sont dessinés au DÉBUT de chaque page (onPage) : le corps
        # commence donc toujours avec la valeur de la passe précédente (stable
        # dès la passe 2 ; multiBuild fait au moins 2 passes avec un TOC).
        self._body_start_prev = getattr(self, '_body_start_page', None)
        self._body_start_page = None

    def afterFlowable(self, flowable):
        # Début du corps = premier signet de niveau 0 (chapitre 1) — robuste aux
        # passes multiBuild (un attribut posé sur un flowable marqueur ne survit
        # pas de façon fiable d'une passe à l'autre).
        if (self._body_start_page is None and hasattr(flowable, 'bookmark_name')
                and getattr(flowable, 'bookmark_level', 0) == 0):
            self._body_start_page = self.page
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            # Numéro AFFICHÉ (arabe remis à 1 au début du corps — le TOC exige un entier)
            if self._body_start_page is not None and self.page >= self._body_start_page:
                display = self.page - self._body_start_page + 1
            else:
                display = self.page
            self.notify('TOCEntry', (level, text, display, key))
            self.canv.bookmarkPage(key)
            self.canv.addOutlineEntry(text, key, level=level, closed=False)

    def footer_text(self, page):
        roman = {1: 'i', 2: 'ii', 3: 'iii', 4: 'iv', 5: 'v', 6: 'vi', 7: 'vii', 8: 'viii'}
        body_start = self._body_start_prev if self._body_start_prev is not None else self._body_start_page
        if body_start is None or page < body_start:
            return roman.get(page, str(page))
        return str(page - body_start + 1)


